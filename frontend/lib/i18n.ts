function humanizeToken(value: string): string {
  return value
    .split("_")
    .filter(Boolean)
    .map((segment) => segment.charAt(0).toUpperCase() + segment.slice(1))
    .join(" ");
}

export function normalizeLocale(value: unknown): AppLocale {
  if (typeof value !== "string") {
    return "en";
  }

  const normalized = value.toLowerCase();
  if (normalized.startsWith("zh")) {
    return "zh-CN";
  }
  return "en";
}

export function translate(locale: AppLocale, key: string, vars?: TranslationVars): string {
  const template = dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
  if (!vars) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (_, token: string) => String(vars[token] ?? `{${token}}`));
}

export function translateToken(locale: AppLocale, token?: string | null): string {
  if (!token) {
    return locale === "zh-CN" ? "未知" : "Unknown";
  }
  return tokenLabels[locale][token] ?? tokenLabels.en[token] ?? humanizeToken(token);
}

export function useI18n() {
  const locale = useAppStore((state) => state.locale);
  const setLocale = useAppStore((state) => state.setLocale);

  return {
    locale,
    setLocale,
    t: (key: string, vars?: TranslationVars) => translate(locale, key, vars),
    token: (token?: string | null) => translateToken(locale, token),
    operationModeLabel: (mode?: string | null) => translateToken(locale, mode),
    draftStatusLabel: (status?: string | null) => translateToken(locale, status),
    publishStatusLabel: (status?: string | null) => translateToken(locale, status),
    taskStatusLabel: (status?: string | null) => translateToken(locale, status),
  };
}
